#!/usr/bin/env python3
"""Writes vk12_bases.h: for each Direct3D 12 interface vk12 implements, a base class that defines every method
of the interface and of the interfaces it inherits (except IUnknown's) as "not implemented". vk12's classes derive
from these and override what the driver uses, so an interface gaining or having methods the driver never calls
doesn't have to be spelled out by hand.

usage: gen_bases.py path/to/d3d12.h [path/to/d3dcommon.h] > vk12_bases.h
The headers are Microsoft's (DirectX-Headers' include/directx, or the Windows SDK's)."""
import re
import sys

WANTED = ["ID3D12Device", "ID3D12CommandQueue", "ID3D12CommandAllocator", "ID3D12GraphicsCommandList",
          "ID3D12Resource", "ID3D12Heap", "ID3D12DescriptorHeap", "ID3D12PipelineState", "ID3D12RootSignature",
          "ID3D12Fence", "ID3D12QueryHeap", "ID3D10Blob"]


def interfaces(text):
    """name -> (base, [method declaration text without the '= 0;'])"""
    found = {}
    for m in re.finditer(r"^\s+(\w+) : public (\w+)\s*\n\s+\{\s*\n\s+public:\n(.*?)^\s+\};", text, re.S | re.M):
        name, base, body = m.groups()
        # Where the header offers two ABIs for methods returning structures, the first is MSVC's and every
        # non-Windows compiler's, which are the ones this is built with
        body = re.sub(r"#if defined\(_MSC_VER\) \|\| !defined\(_WIN32\)\n(.*?)#else\n.*?#endif\n", r"\1", body, flags=re.S)
        methods = [d.strip() for d in re.findall(r"(virtual .*?)= 0;", body, re.S)]
        found.setdefault(name, (base, methods))
    return found


def default(decl):
    ret = decl.split("STDMETHODCALLTYPE")[0].replace("virtual", "").strip()
    if ret == "void":
        return " Unimplemented(__func__);"
    if ret == "HRESULT":
        return " return Unimplemented(__func__);"
    if ret.endswith("*") or ret in ("LPVOID",):
        return " Unimplemented(__func__); return nullptr;"
    if ret in ("UINT", "UINT64", "ULONG", "BOOL", "D3D12_GPU_VIRTUAL_ADDRESS", "SIZE_T"):
        return " Unimplemented(__func__); return 0;"
    return " Unimplemented(__func__); return {};"


def main():
    text = "".join(open(path, encoding="utf-8", errors="replace").read() for path in sys.argv[1:])
    found = interfaces(text)
    out = ["// Generated by gen_bases.py from Microsoft's d3d12.h and d3dcommon.h; do not edit.",
           "// Every method of the interfaces vk12 implements, defined as not implemented.", "",
           "#ifndef RR_VK12_BASES_H", "#define RR_VK12_BASES_H", "", "namespace rr_vk12", "{", "",
           "HRESULT Unimplemented(const char *method);", ""]
    for name in WANTED:
        chain = []
        current = name
        while current != "IUnknown":
            base, methods = found[current]
            chain.append((current, methods))
            current = base
        out.append(f"struct {name}Base : public {name}")
        out.append("{")
        for owner, methods in reversed(chain):
            out.append(f"\t// {owner}")
            for decl in methods:
                decl = re.sub(r"\s+", " ", decl)
                out.append(f"\t{decl} override {{{default(decl)} }}")
        out.append("};")
        out.append("")
    out += ["} // namespace rr_vk12", "", "#endif"]
    print("\n".join(out))


main()
